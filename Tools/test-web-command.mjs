#!/usr/bin/env bun
// `swift package web init` and the ./swiftweb script it writes, on Tests/ConsumerRegression: the script is written (and not over
// a file that is not its own), finds the framework, reports the toolchain, builds a bundle and runs the development loop
// until the page is served. The fixture is left as it was.
// Run by `make web-command-test`; builds into .build/web-command-test.
import assert from "node:assert/strict";
import { spawn, spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { freePort, ROOT } from "./browser-test-support.mjs";

const fixture = join(ROOT, "Tests/ConsumerRegression");
const script = join(fixture, "swiftweb"), resolved = join(fixture, "Package.resolved");
const work = join(ROOT, ".build/web-command-test");
const hadResolved = existsSync(resolved);
const env = { ...process.env, SWIFTUIWEB_BUILD_ROOT: work, SWIFTUIWEB_OPEN_BROWSER: "0" };

function run(command, options = {}) {
  const result = spawnSync(command[0], command.slice(1), { cwd: fixture, env, encoding: "utf8", ...options });
  return { status: result.status, output: (result.stdout ?? "") + (result.stderr ?? "") };
}
/** `pid` and every process below it. */
function descendants(pid) {
  const children = spawnSync("pgrep", ["-P", String(pid)], { encoding: "utf8" }).stdout.split("\n").filter(Boolean).map(Number);
  return [pid, ...children.flatMap(descendants)];
}
const alive = (pid) => { try { process.kill(pid, 0); return true; } catch { return false; } };
const init = (...extra) => run(["swift", "package", "--allow-writing-to-package-directory", "web", "init", ...extra]);

rmSync(script, { force: true });
rmSync(work, { recursive: true, force: true });
let loop = null;
try {
  // The command writes an executable script of its own.
  const written = init();
  assert.equal(written.status, 0, written.output);
  assert.match(written.output, /Wrote .*ConsumerRegression\/swiftweb/);
  assert.ok(statSync(script).mode & 0o100, "the script is executable");
  const text = readFileSync(script, "utf8");
  assert.match(text, /Generated by `swift package web init`/);
  // Single-quoted for the shell: a checkout path with `"`, `$(` or a backtick stays text.
  assert.match(text, /"\$here"\/'\.\.\/\.\.'/, "a path dependency is recorded relative to the package");
  // Writing it again is fine; a file that is someone else's is kept unless --force says otherwise.
  assert.equal(init().status, 0);
  writeFileSync(script, "#!/bin/sh\necho mine\n");
  const refused = init();
  assert.notEqual(refused.status, 0);
  assert.match(refused.output, /was not written by this command/);
  assert.equal(readFileSync(script, "utf8"), "#!/bin/sh\necho mine\n");
  assert.equal(init("--force").status, 0);
  assert.equal(readFileSync(script, "utf8"), text);

  // Help, an unknown command, the toolchain report.
  assert.equal(run(["./swiftweb", "help"]).status, 0);
  const unknown = run(["./swiftweb", "nope"]);
  assert.equal(unknown.status, 2);
  assert.match(unknown.output, /Usage: \.\/swiftweb dev\|build\|run\|doctor/);
  const doctor = run(["./swiftweb", "doctor"]);
  assert.equal(doctor.status, 0, doctor.output);
  assert.match(doctor.output, /wasm sdk/);

  // Somewhere the framework is not resolved, it says what to run.
  const elsewhere = mkdtempSync(join(tmpdir(), "web-command-"));
  try {
    copyFileSync(script, join(elsewhere, "swiftweb"));
    const lost = run([join(elsewhere, "swiftweb"), "doctor"], { cwd: elsewhere, env: { ...env, SWIFTUIWEB_ROOT: "" } });
    assert.equal(lost.status, 2);
    assert.match(lost.output, /swift package resolve/);
  } finally {
    rmSync(elsewhere, { recursive: true, force: true });
  }

  // A build: options after the command reach the launcher.
  const built = run(["./swiftweb", "build", "--configuration", "debug", "--dev-profile", "fast"]);
  assert.equal(built.status, 0, built.output.slice(-3000));
  const bundle = built.output.match(/^Bundle ready: (.+)$/m)?.[1];
  assert.ok(bundle && existsSync(join(bundle, "app.wasm")), "the build leaves a bundle");

  // The development loop: it serves the page, and stops with its process group (Ctrl-C).
  const port = await freePort();
  let output = "";
  loop = spawn("./swiftweb", ["dev", "--port", String(port)], { cwd: fixture, env, stdio: ["ignore", "pipe", "pipe"] });
  loop.stdout.on("data", (chunk) => { output += chunk; });
  loop.stderr.on("data", (chunk) => { output += chunk; });
  const deadline = Date.now() + 240_000;
  while (!/\[watch\] READY/.test(output)) {
    assert.ok(Date.now() < deadline && loop.exitCode === null, `the loop did not get ready:\n${output.slice(-3000)}`);
    await new Promise((done) => setTimeout(done, 250));
  }
  const page = await fetch(`http://127.0.0.1:${port}/`);
  assert.equal(page.status, 200);
  assert.match(await page.text(), /<html/i);
  assert.match(output, /development profile fast/);
} finally {
  // Ctrl-C reaches every process of the loop; here each one is signalled, children first found.
  if (loop && loop.exitCode === null) {
    const tree = descendants(loop.pid);
    for (const pid of tree) { try { process.kill(pid, "SIGINT"); } catch { /* already gone */ } }
    await new Promise((done) => setTimeout(done, 1500));
    const left = tree.filter(alive);
    for (const pid of left) { try { process.kill(pid, "SIGKILL"); } catch { /* stopped */ } }
    assert.deepEqual(left, [], "the loop's processes stop on an interrupt");
  }
  rmSync(script, { force: true });
  if (!hadResolved) rmSync(resolved, { force: true });
}
loop?.stdout.destroy();
loop?.stderr.destroy();
console.log("PASS web command: swift package web init writes ./swiftweb, which reports the toolchain, builds a bundle and serves the development loop");
process.exit(process.exitCode ?? 0);
