#!/usr/bin/env bun
// Writes the data of the site's Performance page from the results of the SwiftUIWeb/React comparison, so the page shows what
// was measured and nothing typed by hand.
//
//   bun Tools/publish-react-comparison.mjs            writes Examples/ShowcaseSite/Features/Performance/Presentation/PerformanceResultsData.swift
//   bun Tools/publish-react-comparison.mjs --check    fails when that file is not what the results would produce
//
// Input: Benchmarks/ReactComparison/results/latest.json (Tools/compare-react.mjs --json).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const INPUT = join(ROOT, "Benchmarks/ReactComparison/results/latest.json");
const OUTPUT = join(ROOT, "Examples/ShowcaseSite/Features/Performance/Presentation/PerformanceResultsData.swift");

const number = (value) => (Number.isFinite(value) ? String(Math.round(value * 1000) / 1000) : "0");
const literal = (text) => JSON.stringify(String(text));
const verdictCase = (verdict) => ({ "B lower": ".reactLower", "B higher": ".reactHigher", "too few samples": ".tooFewSamples" })[verdict] ?? ".same";

/** Whether SwiftUIWeb's worker was throttled at a rate. Rates of 1 are the machine as it is; a rate above 1 with no record of its reach is not. */
export function workerThrottled(meta, rate) {
  return Number(rate) === 1 || meta.throttle?.[rate]?.a === "the page and its workers";
}

/** The PerformanceMetricVO lines of one report (the comparisons of one CPU rate, or of one network profile). */
function metricLines(report) {
  return Object.values(report).map((row) => {
    const c = row.comparison;
    const main = row.comparisonMain ?? c;
    // A result without the virtualized side (an older results file) reads as too few samples, with no number.
    const virtual = row.comparisonVirtual ?? { medianB: NaN, iqrB: 0, verdict: "too few samples" };
    const fields = [
      `id: ${literal(row.id)}`, `unit: ${literal(row.unit)}`,
      `swiftUIWeb: ${number(c.medianA)}`, `mainThread: ${number(main.medianA)}`, `react: ${number(c.medianB)}`,
      `swiftUIWebSpread: ${number(c.iqrA)}`, `mainThreadSpread: ${number(main.iqrA)}`, `reactSpread: ${number(c.iqrB)}`,
      `verdict: ${verdictCase(c.verdict)}`, `mainThreadVerdict: ${verdictCase(main.verdict)}`,
      `reactVirtual: ${number(virtual.medianB)}`, `reactVirtualSpread: ${number(virtual.iqrB)}`, `reactVirtualVerdict: ${verdictCase(virtual.verdict)}`,
    ];
    return `        PerformanceMetricVO(${fields.join(", ")})`;
  });
}

export function render(results) {
  const { meta, cpu } = results;
  const rates = Object.entries(cpu).map(([rate, report]) => {
    const metrics = metricLines(report);
    return `      PerformanceRateVO(cpu: ${rate}, swiftUIWebThrottled: ${workerThrottled(meta, rate)}, metrics: [\n${metrics.join(",\n")},\n      ])`;
  });
  // The network profiles, with the conditions they were emulated with; a results file without them has none.
  const networks = Object.values(results.network ?? {}).map((network) => {
    const metrics = metricLines(network.report);
    const downloadMbps = number((network.downloadThroughput * 8) / 1e6);
    const uploadKbps = Math.round((network.uploadThroughput * 8) / 1000);
    return `      PerformanceNetworkVO(label: ${literal(network.label)}, latency: ${network.latency}, downloadMbps: ${downloadMbps}, uploadKbps: ${uploadKbps}, metrics: [\n${metrics.join(",\n")},\n      ])`;
  });
  return `// Generated by Tools/publish-react-comparison.mjs from Benchmarks/ReactComparison/results/latest.json. Do not edit.

/// What the SwiftUIWeb/React comparison measured, and how.
enum PerformanceResultsData {
  static let results = PerformanceResultsVO(
    date: ${literal(meta.date.slice(0, 10))},
    machine: ${literal(`${meta.machine.cpu}, ${meta.machine.cores} cores, ${meta.machine.memoryGB} GB, ${meta.machine.os}`)},
    browser: ${literal(meta.browser ?? "")},
    rounds: ${meta.rounds},
    rates: [
${rates.join(",\n")},
    ],
    networks: [${networks.length ? `\n${networks.join(",\n")},\n    ` : ""}]
  )
}
`;
}

function main() {
  const text = render(JSON.parse(readFileSync(INPUT, "utf8")));
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(OUTPUT, "utf8"); } catch { /* missing */ }
    if (current !== text) {
      console.error(`${OUTPUT} is not what ${INPUT} produces; run: bun Tools/publish-react-comparison.mjs`);
      process.exit(1);
    }
    console.log("The Performance page's data is current.");
    return;
  }
  writeFileSync(OUTPUT, text);
  console.log(`Wrote ${OUTPUT}`);
}

if (import.meta.main) main();
