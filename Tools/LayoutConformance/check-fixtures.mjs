#!/usr/bin/env bun
// Static checks of the layout conformance setup: every node a fixture names has a probe in both the web app and
// the Apple oracle, fixture ids are unique, and the web app imports the public facade as a BrowserApp.
import { readFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");

/** `repr(list_of_str)`. */
const listRepr = (items) => `[${items.map((item) => (item.includes("'") && !item.includes('"') ? `"${item}"` : `'${item.replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`)).join(", ")}]`;

/** Runs the checks; returns the exit code and prints the report (`FAIL ...` on stderr for the last three). */
export function check(root = ROOT, out = (line) => console.log(line), err = (line) => console.error(line)) {
  const spec = JSON.parse(readFileSync(join(root, "Tools/LayoutConformance/fixtures.json"), "utf8"));
  const expected = new Set(spec.fixtures.flatMap((fixture) => fixture.nodes));
  const files = [join(root, "Tests/Apps/LayoutConformanceApp/main.swift"), join(root, "Tools/LayoutConformance/AppleOracle.swift")];
  let failed = false;
  for (const path of files) {
    const text = readFileSync(path, "utf8");
    const found = new Set([...text.matchAll(/probe\("([^"]+)"\)/g)].map((match) => match[1]));
    // Host IDs are generated by Fixture and therefore don't occur as literals.
    const explicit = [...expected].filter((node) => !node.endsWith(".host"));
    const missing = explicit.filter((node) => !found.has(node)).sort();
    if (missing.length) {
      failed = true;
      out(`FAIL ${basename(path)}: missing probes: ${listRepr(missing)}`);
    } else out(`PASS ${basename(path)}: ${explicit.length} explicit probes`);
  }
  if (new Set(spec.fixtures.map((fixture) => fixture.id)).size !== spec.fixtures.length) {
    failed = true;
    out("FAIL duplicate fixture IDs");
  }
  if (failed) return 1;
  out(`PASS fixture manifest: ${spec.fixtures.length} paired fixtures`);

  // public facade import contract
  const appText = readFileSync(join(root, "Tests/Apps/LayoutConformanceApp/main.swift"), "utf8");
  const packageText = readFileSync(join(root, "Package.swift"), "utf8");
  if (!appText.includes("import SwiftUIWeb\n")) {
    err("FAIL LayoutConformanceApp must import the public SwiftUIWeb facade");
    return 1;
  }
  if (!packageText.includes('.executableTarget(name: "LayoutConformanceApp", dependencies: ["SwiftUIWeb", "SwiftUIWebBrowser"]')) {
    err("FAIL LayoutConformanceApp target must depend on SwiftUIWeb and SwiftUIWebBrowser");
    return 1;
  }
  out("PASS public facade import contract");

  // The Embedded source-lowering pass synthesizes the browser reactor entrypoints only for BrowserApp executables.
  // A plain App compiles but then fails at wasm-ld because run-browser injects exports that have no corresponding
  // symbols.
  if (!appText.includes("struct LayoutConformanceApp: BrowserApp")) {
    err("FAIL LayoutConformanceApp must conform to BrowserApp so Embedded browser entrypoints are synthesized");
    return 1;
  }
  out("PASS Embedded BrowserApp entrypoint contract");
  return 0;
}

if (import.meta.main) process.exit(check());
