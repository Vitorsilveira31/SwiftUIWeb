import Foundation
import PackagePlugin

/// `swift package web init`: writes the `swiftweb` script at the root of the package, which runs SwiftUIWeb's tools for it
/// (`./swiftweb dev`, `./swiftweb build`, `./swiftweb run`, `./swiftweb doctor`).
///
/// It is not called `web`: packages keep their browser target in a `Web` folder, and on a file system that ignores case a
/// file of that name cannot sit next to it.
///
/// The script exists because a development loop cannot live inside a SwiftPM command: the plugin sandbox has no local
/// server, and a `swift package` process holds the lock of the package's `.build` folder for as long as it runs, so a
/// `swift build` or `swift test` in another terminal would wait for the whole session. The script calls the tools from the
/// checkout SwiftPM resolved, outside SwiftPM. Writing it is the one thing that needs the package directory, so run
/// `swift package --allow-writing-to-package-directory web init`.
@main
struct SwiftUIWebWebPlugin: CommandPlugin {
  func performCommand(context: PluginContext, arguments: [String]) async throws {
    let packageRoot = Self.physical(context.package.directoryURL)
    let script = packageRoot.appendingPathComponent("swiftweb")
    switch arguments.first ?? "help" {
    case "init":
      let frameworkRoot = try locateFrameworkRoot(context: context)
      let force = arguments.contains("--force")
      if FileManager.default.fileExists(atPath: script.path), !force,
        let existing = try? String(contentsOf: script, encoding: .utf8), !existing.contains(Self.marker)
      {
        Diagnostics.error("\(script.path) exists and was not written by this command; pass --force to replace it")
        throw WebPluginError.scriptExists
      }
      let text = Self.script(recordedFramework: Self.relativePath(from: packageRoot, to: frameworkRoot))
      try text.write(to: script, atomically: true, encoding: .utf8)
      try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: script.path)
      print("Wrote \(script.path)")
      print("  ./swiftweb dev      build, serve and reload on save")
      print("  ./swiftweb build    release bundle")
      print("  ./swiftweb run      release bundle, served")
      print("  ./swiftweb doctor   what the toolchain is missing")
    default:
      print(
        """
        Usage: swift package --allow-writing-to-package-directory web init [--force]

        Writes ./swiftweb, the script that runs SwiftUIWeb for this package:
          ./swiftweb dev [product]     build, serve, and rebuild and reload when a source file is saved
          ./swiftweb build [product]   release bundle
          ./swiftweb run [product]     release bundle, served
          ./swiftweb doctor            what the toolchain is missing, with the command that installs it

        The development loop is a script and not a `swift package` command because a SwiftPM command cannot start a
        local server and holds the lock of .build while it runs.
        """)
    }
  }

  /// The text every script this command writes holds, so a later `init` knows the file is its own.
  static let marker = "Generated by `swift package web init` (SwiftUIWeb)"

  /// `text` as one POSIX shell word in single quotes: each `'` closes the quote, adds an escaped quote and reopens it.
  static func shellSingleQuoted(_ text: String) -> String {
    "'" + text.split(separator: "'", omittingEmptySubsequences: false).joined(separator: "'\\''") + "'"
  }

  /// The script. `recordedFramework` is where the framework was when it was written, relative to the package (a path
  /// dependency); a checkout below `.build/checkouts` is found on its own.
  static func script(recordedFramework: String?) -> String {
    // The recorded path is a directory name chosen by someone else: single quotes keep `"`, `$(`, backticks and `\` inert.
    let recorded = recordedFramework.map { "\"$here\"/" + shellSingleQuoted($0) + " " } ?? ""
    return """
      #!/usr/bin/env bash
      # \(marker). Runs SwiftUIWeb's tools for this package from the checkout SwiftPM
      # resolved; write it again with `swift package --allow-writing-to-package-directory web init`.
      set -euo pipefail
      here="$(cd "$(dirname "$0")" && pwd -P)"
      framework() {
        if [[ -n "${SWIFTUIWEB_ROOT:-}" ]]; then printf '%s\\n' "$SWIFTUIWEB_ROOT"; return 0; fi
        local candidate
        for candidate in \(recorded)"$here"/.build/checkouts/*; do
          if [[ -f "$candidate/Tools/swiftuiweb-run.swift" ]]; then (cd "$candidate" && pwd); return 0; fi
        done
        return 1
      }
      root="$(framework)" || {
        echo "SwiftUIWeb is not resolved for this package yet: run \\`swift package resolve\\` and try again (or set SWIFTUIWEB_ROOT)." >&2
        exit 2
      }
      command="${1:-dev}"
      [[ $# -eq 0 ]] || shift
      case "$command" in
        dev) exec swift "$root/Tools/swiftuiweb-run.swift" --path "$here" --watch "$@" ;;
        build) exec swift "$root/Tools/swiftuiweb-run.swift" --path "$here" --configuration release --build-only "$@" ;;
        run) exec swift "$root/Tools/swiftuiweb-run.swift" --path "$here" --configuration release "$@" ;;
        doctor) exec /bin/bash "$root/Tools/toolchain-report.sh" --verbose ;;
        *)
          echo "Usage: ./swiftweb dev|build|run|doctor [product] [options]"
          echo "  dev      build, serve, and rebuild and reload when a source file is saved (debug)"
          echo "  build    release bundle"
          echo "  run      release bundle, served"
          echo "  doctor   what the toolchain is missing, with the command that installs it"
          echo "Options after the command go to SwiftUIWeb's launcher (--product NAME, --port N, --dev-profile embedded, ...)."
          [[ "$command" == help || "$command" == -h || "$command" == --help ]] || exit 2
          ;;
      esac

      """
  }

  /// The path with every symbolic link resolved, as `pwd -P` prints it in the script. Foundation's
  /// `resolvingSymlinksInPath` is not that: it drops a leading `/private` (`/private/tmp` becomes `/tmp`), and a relative
  /// path computed from one form and followed from the other leads somewhere else.
  static func physical(_ url: URL) -> URL {
    guard let resolved = realpath(url.path, nil) else { return url.standardizedFileURL }
    defer { free(resolved) }
    return URL(fileURLWithPath: String(cString: resolved), isDirectory: true)
  }

  /// `to` relative to `from`, or nil when it is below `from`'s `.build` (the script finds those itself).
  static func relativePath(from: URL, to: URL) -> String? {
    let base = from.pathComponents, target = to.pathComponents
    var common = 0
    while common < base.count, common < target.count, base[common] == target[common] { common += 1 }
    let rest = Array(target[common...])
    if common == base.count, rest.first == ".build" { return nil }
    let parts = Array(repeating: "..", count: base.count - common) + rest
    return parts.isEmpty ? "." : parts.joined(separator: "/")
  }

  private func locateFrameworkRoot(context: PluginContext) throws -> URL {
    if let configured = ProcessInfo.processInfo.environment["SWIFTUIWEB_ROOT"] {
      return Self.physical(URL(fileURLWithPath: configured))
    }
    let launcher = "Tools/swiftuiweb-run.swift"
    for dependency in context.package.dependencies {
      let directory = Self.physical(dependency.package.directoryURL)
      if FileManager.default.fileExists(atPath: directory.appendingPathComponent(launcher).path) { return directory }
    }
    let local = Self.physical(context.package.directoryURL)
    if FileManager.default.fileExists(atPath: local.appendingPathComponent(launcher).path) { return local }
    Diagnostics.error("Add SwiftUIWeb as a package dependency, or set SWIFTUIWEB_ROOT")
    throw WebPluginError.frameworkNotFound
  }
}

private enum WebPluginError: Error, CustomStringConvertible {
  case frameworkNotFound
  case scriptExists

  var description: String {
    switch self {
    case .frameworkNotFound: return "SwiftUIWeb was not found among this package's dependencies."
    case .scriptExists: return "./swiftweb exists and is not this command's."
    }
  }
}
