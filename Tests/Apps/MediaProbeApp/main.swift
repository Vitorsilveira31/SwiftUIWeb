import SwiftUIWeb
import SwiftUIWebBrowser
import SwiftUIWebBrowserIO
import SwiftUIWebAVFoundation
import SwiftUIWebAVKit

/// The fixture for `Tools/test-media-worker-browser.mjs`: an AVPlayer-shaped player over a short local file (`/probe.wav`,
/// `/probe.mp4` or `/probe.webm`, which the test generates) and one button per thing the test reads or does. Every
/// result goes to the `log` text as one line, so the test sees what the app's Swift code read, in the Worker or on the main thread.
///   R|<wall ms>|<time ms>|<rate x1000>|<status>|<item status>|<timeControlStatus>|<duration ms>|<volume x1000>|<muted>  a read
///   P|<wall ms>|<time ms>   the 0.5 s periodic observer; F|<count> how often the 50 ms one fired
///   B|<wall ms>|<time ms>   a boundary observer (1.2 s and 2.5 s)
///   S|<label>|<finished>|<time ms>   a seek completion
@Observable @MainActor final class MediaProbeModel {
  var lines: [String] = []
  var fast = 0
  var overlayTaps = 0
  let player = AVPlayer(url: URL(string: "/probe.wav")!)
  var tokens: [Any] = []

  init() { player.isMuted = true }

  // Int is 32 bits on wasm32: a wall-clock time in milliseconds needs Int64.
  nonisolated static func wallMilliseconds() -> Int64 { Int64(_swiftUIWebWallClockMilliseconds().rounded()) }
  nonisolated static func milliseconds(_ seconds: Double) -> Int { seconds.isFinite ? Int((seconds * 1000).rounded()) : -1 }

  func read() -> String {
    let item = player.currentItem
    let fields: [String] = [
      "R", String(Self.wallMilliseconds()), String(Self.milliseconds(player.currentTime().seconds)), String(Int((player.rate * 1000).rounded())),
      String(player.status.rawValue), String(item?.status.rawValue ?? -1), String(player.timeControlStatus.rawValue),
      String(Self.milliseconds(item?.duration.seconds ?? .nan)), String(Int((player.volume * 1000).rounded())), player.isMuted ? "1" : "0"
    ]
    return fields.joined(separator: "|")
  }

  func log(_ line: String) { lines.append(line) }

  func burst(count: Int, spacingNanoseconds: UInt64) {
    Task { @MainActor in
      for _ in 0..<count {
        lines.append(read())
        try? await Task.sleep(nanoseconds: spacingNanoseconds)
      }
      lines.append("burst-done")
    }
  }

  func seek(_ label: String, to seconds: Double) {
    // AVFoundation calls the handler from its own queue; the model is main-actor state, so the line goes there.
    let player = self.player
    player.seek(to: CMTime(seconds: seconds, preferredTimescale: 600)) { finished in
      let line = "S|\(label)|\(finished ? 1 : 0)|\(Self.milliseconds(player.currentTime().seconds))"
      Task { @MainActor in self.log(line) }
    }
  }

  /// `MainActor.assumeIsolated` inside each kind of AV callback, as Apple's documentation allows (the callbacks run on the
  /// queue given, and on the main queue for nil/.main). The line is written from inside it: `AI|<kind>`.
  func assumeInSeek() {
    player.seek(to: CMTime(seconds: 1, preferredTimescale: 600)) { _ in
      MainActor.assumeIsolated { self.log("AI|seek") }
    }
  }

  func assumeInObservers() {
    tokens.append(player.addPeriodicTimeObserver(forInterval: CMTime(seconds: 0.5, preferredTimescale: 600), queue: .main) { _ in
      MainActor.assumeIsolated { self.log("AI|periodic") }
    })
    tokens.append(player.addBoundaryTimeObserver(forTimes: [NSValue(time: CMTime(seconds: 0.2, preferredTimescale: 600))], queue: nil) {
      MainActor.assumeIsolated { self.log("AI|boundary") }
    })
  }

  func load(_ path: String) {
    player.replaceCurrentItem(with: AVPlayerItem(url: URL(string: path)!))
  }
}

private struct MediaProbeRoot: View {
  @State private var model = MediaProbeModel()
  @State private var showsView = true

  var body: some View {
    VStack(alignment: .leading) {
      if showsView {
        // A frame the controls fit in (Tools/test-avkit-controls-browser.mjs); the overlay is the app's own content under them.
        // Two WebVTT tracks (generated by the test): the English one is the browser's default, so the subtitles menu starts on it.
        VideoPlayer(
          player: model.player,
          captionTracks: [
            CaptionTrack(url: URL(string: "/captions-en.vtt")!, languageCode: "en", label: "English", isDefault: true),
            CaptionTrack(url: URL(string: "/captions-pt.vtt")!, languageCode: "pt", label: "Português"),
          ]
        ) {
          VStack {
            HStack {
              Button("Tap overlay") { model.overlayTaps += 1 }.accessibilityIdentifier("overlay-button")
              Spacer()
            }
            Spacer()
          }
          .padding(8)
        }
        .frame(height: 270)
      }
      HStack {
        Button("hide-view") { showsView = false }.accessibilityIdentifier("hide-view")
        Button("show-view") { showsView = true }.accessibilityIdentifier("show-view")
      }
      HStack {
        Button("play") { model.player.play() }.accessibilityIdentifier("play")
        Button("pause") { model.player.pause() }.accessibilityIdentifier("pause")
        Button("mute") { model.player.isMuted = true }.accessibilityIdentifier("mute")
        Button("unmute") { model.player.isMuted = false }.accessibilityIdentifier("unmute")
        Button("volume") { model.player.volume = 0.5 }.accessibilityIdentifier("volume")
        Button("rate2") { model.player.rate = 2 }.accessibilityIdentifier("rate2")
        Button("rate1") { model.player.rate = 1 }.accessibilityIdentifier("rate1")
      }
      HStack {
        Button("seek2") { model.seek("two", to: 2) }.accessibilityIdentifier("seek2")
        Button("race") {
          model.seek("A", to: 4)
          model.seek("B", to: 1)
        }.accessibilityIdentifier("race")
        Button("seekEnd") {
          let end = model.player.currentItem?.duration.seconds ?? 0
          model.seek("end", to: max(0, end - 0.3))
        }.accessibilityIdentifier("seekEnd")
        Button("seekBeyond") { model.seek("beyond", to: 1000) }.accessibilityIdentifier("seekBeyond")
        Button("seekStart") { model.seek("start", to: 0) }.accessibilityIdentifier("seekStart")
      }
      HStack {
        Button("read") { model.log(model.read()) }.accessibilityIdentifier("read")
        Button("burst") { model.burst(count: 100, spacingNanoseconds: 20_000_000) }.accessibilityIdentifier("burst")
        Button("periodic") {
          model.tokens.append(model.player.addPeriodicTimeObserver(forInterval: CMTime(seconds: 0.5, preferredTimescale: 600), queue: nil) { time in
            let line = "P|\(MediaProbeModel.wallMilliseconds())|\(MediaProbeModel.milliseconds(time.seconds))"
            Task { @MainActor in model.log(line) }
          })
        }.accessibilityIdentifier("periodic")
        Button("fast") {
          model.tokens.append(model.player.addPeriodicTimeObserver(forInterval: CMTime(seconds: 0.05, preferredTimescale: 600), queue: nil) { _ in
            Task { @MainActor in model.fast += 1 }
          })
        }.accessibilityIdentifier("fast")
        Button("boundary") {
          let times = [1.2, 2.5].map { NSValue(time: CMTime(seconds: $0, preferredTimescale: 600)) }
          let player = model.player
          model.tokens.append(model.player.addBoundaryTimeObserver(forTimes: times, queue: nil) {
            let line = "B|\(MediaProbeModel.wallMilliseconds())|\(MediaProbeModel.milliseconds(player.currentTime().seconds))"
            Task { @MainActor in model.log(line) }
          })
        }.accessibilityIdentifier("boundary")
        Button("unobserve") {
          for token in model.tokens { model.player.removeTimeObserver(token) }
          model.tokens.removeAll()
        }.accessibilityIdentifier("unobserve")
      }
      HStack {
        Button("ai-action") { MainActor.assumeIsolated { model.log("AI|action") } }.accessibilityIdentifier("ai-action")
        Button("ai-seek") { model.assumeInSeek() }.accessibilityIdentifier("ai-seek")
        Button("ai-observers") { model.assumeInObservers() }.accessibilityIdentifier("ai-observers")
      }
      HStack {
        Button("bad") { model.load("/missing.wav") }.accessibilityIdentifier("bad")
        Button("wav") { model.load("/probe.wav") }.accessibilityIdentifier("wav")
        Button("mp4") { model.load("/probe.mp4") }.accessibilityIdentifier("mp4")
        Button("webm") { model.load("/probe.webm") }.accessibilityIdentifier("webm")
      }
      Text("fast \(model.fast)").accessibilityIdentifier("fast-count")
      Text("overlay taps \(model.overlayTaps)").accessibilityIdentifier("overlay-taps")
      Text(model.lines.joined(separator: "\n")).accessibilityIdentifier("log")
    }
    .padding()
  }
}

@main
private struct MediaProbeApp: BrowserApp {
  var body: some View {
    WindowGroup { MediaProbeRoot() }
  }
}
